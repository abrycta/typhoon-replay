"""Regenerate 10_storms.sql from the pipeline's IBTrACS Parquet (deterministic output).

Usage (from the repo root, after `uv run python -m typhoon.ibtracs` in pipeline/):
  pipeline/.venv/bin/python contracts/db/seed/build_seed.py

The generated SQL is committed, so CI and local dev never need data/ (which is gitignored).
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
IBTRACS = ROOT / "data/processed/ibtracs"
CROSSWALK = ROOT / "pipeline/crosswalk/pagasa_names_sid.csv"
OUT = Path(__file__).resolve().parent / "10_storms.sql"

# Fixture storms: PH and JP impacts, intensity extremes, a PAGASA-only name, and a 1940s unnamed storm
# with no intensity data (exercises "omit, never null").
SIDS = [
    "2013306N07162",  # Haiyan / Yolanda: the reference storm (Tacloban)
    "2021346N05145",  # Rai / Odette
    "2020299N11144",  # Goni / Rolly
    "2009268N14128",  # Ketsana / Ondoy (Manila)
    "2019278N16165",  # Hagibis (Kanto)
    "2018239N11161",  # Jebi (Kansai)
    "2023207N09141",  # Khanun (Okinawa / Naha)
    "2022254N24143",  # Nanmadol (Kyushu)
    "1946316N07133",  # Unnamed 1946, PH landfall, no wind data
]
# JMA typhoon numbers (season, number) -> localNames.ja = 台風第{n}号
JMA_NUMBER = {
    "2013306N07162": 30, "2021346N05145": 22, "2020299N11144": 19, "2009268N14128": 16,
    "2019278N16165": 19, "2018239N11161": 21, "2023207N09141": 6, "2022254N24143": 14,
}
NATURE = {"DS": "disturbance", "TS": "tropical", "ET": "extratropical", "SS": "subtropical",
          "NR": "not-reported", "MX": "mixed"}


def q(v) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)) or v is pd.NaT:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, float):
        return str(int(round(v))) if float(v).is_integer() else repr(round(v, 4))
    if isinstance(v, pd.Timestamp):
        return "'" + v.tz_convert("UTC").strftime("%Y-%m-%dT%H:%M:%SZ") + "'"
    return "'" + str(v).replace("'", "''") + "'"


def i(v):
    return None if v is None or pd.isna(v) else int(round(float(v)))


def lon180(lon: float) -> float:
    return round(lon - 360 if lon > 180 else lon, 4)


def point(lon: float, lat: float) -> str:
    return f"ST_SetSRID(ST_MakePoint({lon180(lon)}, {round(lat, 4)}), 4326)::geography"


def pick(*vals):
    for agency, v in vals:
        if v is not None and not pd.isna(v):
            return agency, int(round(float(v)))
    return None, None


def main() -> None:
    st = pd.read_parquet(IBTRACS / "storms.parquet").set_index("sid")
    fx = pd.read_parquet(IBTRACS / "fixes.parquet")
    fx = fx[fx.sid.isin(SIDS)].sort_values(["sid", "iso_time"])
    pagasa = {r["sid"]: r for r in csv.DictReader(CROSSWALK.open()) if r["status"] == "matched"}

    out = ["-- Generated by build_seed.py from IBTrACS v04r01 (WP). Do not edit by hand.", ""]
    for sid in SIDS:
        s = st.loc[sid]
        rows = fx[fx.sid == sid]
        best = rows[rows.iflag.str.contains("O", na=False)]
        name_raw = str(s["name"])
        name = "Unnamed" if name_raw in ("UNNAMED", "NOT_NAMED") else name_raw.title()
        peak_agency, peak_wind = pick(("jtwc", s.max_usa_wind_kt), ("jma", s.max_tokyo_wind_kt),
                                      ("wmo", s.max_wmo_wind_kt))
        min_p = {"jtwc": s.min_usa_pres_hpa, "jma": s.min_tokyo_pres_hpa, "wmo": s.min_wmo_pres_hpa}.get(peak_agency)
        if min_p is None or pd.isna(min_p):
            _, min_p = pick(("jtwc", s.min_usa_pres_hpa), ("jma", s.min_tokyo_pres_hpa), ("wmo", s.min_wmo_pres_hpa))
        countries = [c for c, t in sorted(
            [("PH", s.first_ph_landfall_time), ("JP", s.first_jp_landfall_time)],
            key=lambda ct: (pd.isna(ct[1]), ct[1] if not pd.isna(ct[1]) else pd.Timestamp(0, tz="UTC")))
            if not pd.isna(t)]
        jma_no = JMA_NUMBER.get(sid)
        name_ja = f"台風第{jma_no}号" if jma_no else None
        pg = pagasa.get(sid)
        search = " | ".join(x.lower() for x in [name, name_raw, pg["pagasa_name"] if pg else None, name_ja] if x)
        peak_pos = point(s.peak_lon, s.peak_lat) if peak_wind is not None else "NULL"
        peak_at = q(pd.Timestamp(s.peak_time, tz="UTC")) if peak_wind is not None else "NULL"
        cols = dict(
            sid=q(sid), season=q(int(s.season)), basin=q(str(s.basin)), number=q(i(rows.number.iloc[0])),
            name=q(name), name_ibtracs=q(name_raw), name_ja=q(name_ja), atcf_id=q(s.usa_atcf_id if isinstance(s.usa_atcf_id, str) else None),
            jma_number=q(jma_no), track_type=q(str(s.track_type)),
            started_at=q(best.iso_time.min()), ended_at=q(best.iso_time.max()), fix_count=q(len(best)),
            peak_wind_kt=q(peak_wind), peak_wind_agency=q(peak_agency), peak_at=peak_at, peak_position=peak_pos,
            min_pressure_hpa=q(i(min_p)),
            jtwc_max_wind_kt=q(i(s.max_usa_wind_kt)), jtwc_min_pressure_hpa=q(i(s.min_usa_pres_hpa)),
            jma_max_wind_kt=q(i(s.max_tokyo_wind_kt)), jma_min_pressure_hpa=q(i(s.min_tokyo_pres_hpa)),
            wmo_max_wind_kt=q(i(s.max_wmo_wind_kt)), wmo_min_pressure_hpa=q(i(s.min_wmo_pres_hpa)),
            landfall_countries="ARRAY[" + ",".join(q(c) for c in countries) + "]::text[]",
            replay_available=q(sid == "2013306N07162"), search_text=q(search),
        )
        out.append(f"-- {name} {int(s.season)}" + (f" / {pg['pagasa_name']}" if pg else ""))
        out.append(f"INSERT INTO catalog.storm ({', '.join(cols)}) VALUES\n  ({', '.join(cols.values())});")

        vals = []
        for _, r in best.iterrows():
            agency, wind = pick(("jtwc", r.usa_wind_kt), ("jma", r.tokyo_wind_kt), ("wmo", r.wmo_wind_kt))
            _, pres = pick(("jtwc", r.usa_pres_hpa), ("jma", r.tokyo_pres_hpa), ("wmo", r.wmo_pres_hpa))
            sshs = i(r.usa_sshs)
            vals.append("  (" + ", ".join([
                q(sid), q(r.iso_time), point(r.lon, r.lat), q(wind), q(agency), q(pres), q(i(r.usa_gust_kt)),
                q(i(r.usa_wind_kt)), q(i(r.usa_pres_hpa)), q(i(r.tokyo_wind_kt)), q(i(r.tokyo_pres_hpa)),
                q(i(r.tokyo_grade) if i(r.tokyo_grade) and 2 <= i(r.tokyo_grade) <= 9 else None),
                q(sshs if sshs is not None and -5 <= sshs <= 5 else None),
                q(NATURE.get(str(r.nature))), q(i(r.dist2land_km)), q(i(r.storm_speed_kt)), q(i(r.storm_dir_deg)),
            ]) + ")")
        out.append("INSERT INTO catalog.storm_fix (sid, observed_at, position, wind_kt, wind_agency, pressure_hpa, gust_kt, "
                   "jtwc_wind_kt, jtwc_pressure_hpa, jma_wind_kt, jma_pressure_hpa, jma_grade, sshs_category, nature, "
                   "dist_to_land_km, speed_kt, direction_deg) VALUES\n" + ",\n".join(vals) + ";")

        # Landfalls: first fix of each run of track segments crossing into a covered country.
        seq = 0
        lf = []
        for country, col in (("PH", "seg_hits_ph"), ("JP", "seg_hits_jp")):
            prev = False
            for _, r in rows.iterrows():
                if bool(r[col]) and not prev:
                    lf.append((r.iso_time, country, r.lon, r.lat))
                prev = bool(r[col])
        for t, country, lon, lat in sorted(lf):
            seq += 1
            out.append(f"INSERT INTO catalog.storm_landfall (sid, seq, country, at, position) VALUES "
                       f"({q(sid)}, {seq}, {q(country)}, {q(t)}, {point(lon, lat)});")
        if pg:
            out.append(f"INSERT INTO catalog.pagasa_name (sid, pagasa_name, intl_name, season, source_url) VALUES "
                       f"({q(sid)}, {q(pg['pagasa_name'])}, {q(pg['intl_name'])}, {int(pg['season'])}, {q(pg['source_url'])});")
        out.append("")

    out.append("-- Best-track LineStrings for /v1/hits.")
    out.append("UPDATE catalog.storm s SET track = t.line FROM (\n"
               "  SELECT sid, ST_MakeLine(position::geometry ORDER BY observed_at)::geography AS line\n"
               "  FROM catalog.storm_fix GROUP BY sid HAVING count(*) > 1) t\nWHERE t.sid = s.sid;")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
