//! Regenerates `crates/contract/src/generated.rs` from the bundled contract (`contracts/dist/openapi.json`):
//! every `components.schemas` entry becomes a serde type via typify. Run from `api/rust`:
//! `cargo run -p codegen` (after `npm run bundle` in `contracts/`). CI regenerates and fails on a diff.

use std::{env, fs, path::PathBuf};

use serde_json::Value;
use typify::{TypeSpace, TypeSpaceSettings};

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let bundle = env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("../../contracts/dist/openapi.json"));
    let text = fs::read_to_string(&bundle).unwrap_or_else(|e| panic!("read {}: {e}", bundle.display()));
    let mut doc: Value = serde_json::from_str(&text).expect("contract bundle is JSON");
    let mut schemas = doc["components"]["schemas"].take();
    rewrite_refs(&mut schemas);
    let schema = serde_json::json!({
        "$schema": "http://json-schema.org/draft-07/schema#",
        "definitions": schemas,
    });
    let root_schema: schemars::schema::RootSchema =
        serde_json::from_value(schema).expect("components.schemas is a JSON Schema set");

    let mut space = TypeSpace::new(TypeSpaceSettings::default().with_struct_builder(false));
    space
        .add_root_schema(root_schema)
        .expect("typify accepts the contract schemas");
    let file: syn::File = syn::parse2(space.to_stream()).expect("typify emits valid Rust");
    let out = format!(
        "// @generated by `cargo run -p codegen` from contracts/dist/openapi.json (contract {}). Do not edit.\n\
         #![allow(clippy::all, missing_docs, unused_imports)]\n\n{}",
        doc["info"]["version"].as_str().unwrap_or("?"),
        prettyplease::unparse(&file)
    );
    let target = root.join("crates/contract/src/generated.rs");
    fs::write(&target, out).expect("write generated.rs");
    eprintln!("wrote {}", target.display());
}

/// `#/components/schemas/X` → `#/definitions/X`; OpenAPI-only keywords typify does not need are dropped.
fn rewrite_refs(v: &mut Value) {
    match v {
        Value::Object(map) => {
            if let Some(Value::String(r)) = map.get_mut("$ref") {
                *r = r.replace("#/components/schemas/", "#/definitions/");
            }
            map.remove("discriminator");
            map.remove("example");
            map.retain(|k, _| !k.starts_with("x-"));
            map.values_mut().for_each(rewrite_refs);
        }
        Value::Array(items) => items.iter_mut().for_each(rewrite_refs),
        _ => {}
    }
}
