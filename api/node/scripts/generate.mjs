// Contract-first code generation (run before typecheck, dev and deploy): everything the backend knows about the API
// surface comes from the bundled contract, contracts/dist/openapi.json (`npm --prefix ../../contracts run bundle`).
//
//   src/generated/contract.d.ts   openapi-typescript: paths, operations and component schemas as TypeScript types
//   src/generated/operations.ts   one entry per operation: method, path, Hono route, parameters (name, location, type)
//   src/generated/validators.js   Ajv standalone validators for each operation's parameters, compiled here to plain
//                                 JavaScript, because Workers forbid code generation from strings at runtime
//   src/generated/openapi.ts      the bundle as a string literal (served unchanged at /v1/openapi.json), its version
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const bundlePath = join(here, '../../../contracts/dist/openapi.json');
const out = join(here, '../src/generated');

let text;
try {
  text = readFileSync(bundlePath, 'utf8');
} catch {
  console.error(`No contract bundle at ${bundlePath}: run \`npm --prefix ../../contracts ci && npm --prefix ../../contracts run bundle\``);
  process.exit(1);
}
const spec = JSON.parse(text);
mkdirSync(out, { recursive: true });

const resolve = (ref) =>
  ref
    .slice(2)
    .split('/')
    .reduce((node, key) => node[key.replace(/~1/g, '/').replace(/~0/g, '~')], spec);

/** Inline every $ref and drop documentation-only keywords, so a parameter schema stands alone. */
const DOC_KEYS = new Set(['title', 'description', 'example', 'examples', 'default', 'deprecated']);
function standalone(schema) {
  if (Array.isArray(schema)) return schema.map(standalone);
  if (!schema || typeof schema !== 'object') return schema;
  if (schema.$ref) return standalone(resolve(schema.$ref));
  return Object.fromEntries(
    Object.entries(schema)
      .filter(([k]) => !DOC_KEYS.has(k) && !k.startsWith('x-'))
      .map(([k, v]) => [k, standalone(v)]),
  );
}

const operations = {};
const schemas = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op || typeof op !== 'object' || !op.operationId) continue;
    const params = (op.parameters ?? []).map((p) => (p.$ref ? resolve(p.$ref) : p));
    const validated = params.filter((p) => p.in === 'query' || p.in === 'path');
    const properties = {};
    for (const p of validated) properties[p.name] = standalone(p.schema);
    schemas[op.operationId] = {
      type: 'object',
      properties,
      required: validated.filter((p) => p.required).map((p) => p.name),
    };
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      route: path.replace(/\{([^}]+)\}/g, ':$1'),
      params: validated.map((p) => ({
        name: p.name,
        in: p.in,
        type: standalone(p.schema).type ?? 'string',
        required: Boolean(p.required),
      })),
    };
  }
}

// Parameters arrive as strings; src/platform/params.ts converts integers and numbers strictly before validation, so
// the validators run without type coercion. allErrors: every bad parameter is reported, each with its own pointer.
const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true, lines: false } });
for (const [id, schema] of Object.entries(schemas)) ajv.addSchema(schema, id);
const mapping = Object.fromEntries(Object.keys(schemas).map((id) => [id, id]));
// Ajv's standalone output require()s its runtime helper for string lengths in code points; inline it, so the module
// is plain ESM with no runtime dependency on Ajv.
const code = standaloneCode(ajv, mapping).replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  '((s) => { let n = 0; for (const _ of s) n++; return n; })',
);
if (/\brequire\(|new Function|\beval\(/.test(code)) throw new Error('validators.js must not require(), eval or build functions');
writeFileSync(join(out, 'validators.js'), `// Generated by scripts/generate.mjs from contracts/dist/openapi.json. Do not edit.\n${code}\n`);
writeFileSync(
  join(out, 'validators.d.ts'),
  `// Generated by scripts/generate.mjs. Do not edit.
export interface ParamError { instancePath: string; keyword: string; params: Record<string, unknown>; message?: string }
export type ParamValidator = ((data: unknown) => boolean) & { errors?: ParamError[] | null };
${Object.keys(schemas)
  .map((id) => `export declare const ${id}: ParamValidator;`)
  .join('\n')}
`,
);

const ids = Object.keys(operations);
writeFileSync(
  join(out, 'operations.ts'),
  `// Generated by scripts/generate.mjs from contracts/dist/openapi.json. Do not edit.
export type OperationId = ${ids.map((id) => JSON.stringify(id)).join(' | ')};
export interface ParamSpec { readonly name: string; readonly in: 'query' | 'path'; readonly type: string; readonly required: boolean }
export interface OperationSpec { readonly method: string; readonly path: string; readonly route: string; readonly params: readonly ParamSpec[] }
export const OPERATIONS: { readonly [K in OperationId]: OperationSpec } = ${JSON.stringify(operations, null, 2)};
`,
);

writeFileSync(
  join(out, 'openapi.ts'),
  `// Generated by scripts/generate.mjs. Do not edit.
export const CONTRACT_VERSION = ${JSON.stringify(spec.info.version)};
export const OPENAPI_JSON = ${JSON.stringify(text)};
`,
);

const ast = await openapiTS(spec, { alphabetize: true });
writeFileSync(join(out, 'contract.d.ts'), `// Generated by openapi-typescript (scripts/generate.mjs). Do not edit.\n${astToString(ast)}`);

console.log(`generated ${ids.length} operations for contract ${spec.info.version} in src/generated/`);
