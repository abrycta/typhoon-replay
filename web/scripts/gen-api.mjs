#!/usr/bin/env node
// Regenerate src/api/generated/ from the contract bundle (contracts/dist/openapi.json):
//   schema.d.ts   openapi-typescript `paths`/`components` types (never hand-edited)
//   examples.json the named response examples per operation, used by the MSW mock handlers
//
// Usage: npm run gen:api            (bundles the contract first if dist/ is missing)
//        npm run gen:api -- --check (fail if the committed files are stale; for CI)
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = resolve(web, "../contracts");
const bundle = join(contracts, "dist/openapi.json");
const outDir = join(web, "src/api/generated");
const check = process.argv.includes("--check");

const bin = (name) => join(contracts, "node_modules/.bin", name);
if (!existsSync(bin("openapi-typescript"))) {
  console.log("Installing contracts/ tooling (npm ci)");
  execFileSync("npm", ["ci", "--no-audit", "--no-fund"], { cwd: contracts, stdio: "inherit" });
}
if (!existsSync(bundle) || check) {
  execFileSync("npm", ["run", "bundle"], { cwd: contracts, stdio: "inherit" });
}

// openapi-typescript must run from outside contracts/ (it would pick up redocly.yaml there).
const types = execFileSync(bin("openapi-typescript"), [bundle], { cwd: web, encoding: "utf8" });
const header = "// Generated by web/scripts/gen-api.mjs from contracts/dist/openapi.json. Do not edit.\n";

const spec = JSON.parse(readFileSync(bundle, "utf8"));
const deref = (node) => {
  if (!node?.$ref) return node;
  return deref(node.$ref.replace(/^#\//, "").split("/").reduce((o, k) => o?.[k], spec));
};
const examples = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op?.operationId) continue;
    for (const [status, res] of Object.entries(op.responses ?? {})) {
      for (const [type, media] of Object.entries(res.content ?? {})) {
        const named = Object.fromEntries(Object.entries(media.examples ?? {}).map(([k, v]) => [k, deref(v).value]));
        if (media.example !== undefined) named.default = media.example;
        if (!Object.keys(named).length) continue;
        ((examples[op.operationId] ??= { method, path, responses: {} }).responses[status] ??= {})[type] = named;
      }
    }
  }
}

const files = {
  "schema.d.ts": header + types,
  "examples.json": JSON.stringify({ contractVersion: spec.info.version, operations: examples }, null, 2) + "\n",
};
let stale = false;
mkdirSync(outDir, { recursive: true });
for (const [name, text] of Object.entries(files)) {
  const target = join(outDir, name);
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current === text) continue;
  if (check) {
    console.error(`stale: src/api/generated/${name} (run npm run gen:api)`);
    stale = true;
  } else {
    writeFileSync(target, text);
    console.log(`wrote src/api/generated/${name}`);
  }
}
if (stale) process.exit(1);
console.log(`contract ${spec.info.version}: ${Object.keys(examples).length} operations with examples`);
