// Writes src/features/under-the-hood/conformance.json from each backend's latest passing CI run on main.
//   node scripts/conformance-from-ci.mjs              (needs `gh` with read access to Actions; GH_TOKEN in CI)
//   node scripts/conformance-from-ci.mjs --from <dir> (reads <dir>/<impl>/<impl>-conformance.json instead)
// Each backend workflow (.github/workflows/<impl>.yml) uploads `<impl>-conformance-results`, which holds
// <impl>-conformance.json (contracts/conformance/scripts/summarize.mjs). CI runs this before the build, so the
// bundled table always shows the run it names. A backend whose artifact can't be found keeps the entry already
// in the file (it names its own run), with a warning.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const IMPLS = ["java", "node", "rust", "go"];
const RUNS_TO_TRY = 5; // older runs' artifacts may have expired or predate the summary
const target = new URL("../src/features/under-the-hood/conformance.json", import.meta.url).pathname;
const repo = process.env.GITHUB_REPOSITORY ?? "abrycta/typhoon-replay";
const fromIdx = process.argv.indexOf("--from");
const fromDir = fromIdx > 0 ? process.argv[fromIdx + 1] : undefined;

const current = existsSync(target) ? JSON.parse(readFileSync(target, "utf8")) : { backends: {} };
const warn = (msg) => console.log(process.env.GITHUB_ACTIONS ? `::warning title=Conformance figures::${msg}` : `warning: ${msg}`);
const gh = (...args) => execFileSync("gh", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

function fromCi(impl) {
  let runs;
  try {
    runs = JSON.parse(gh("api", `repos/${repo}/actions/workflows/${impl}.yml/runs?branch=main&event=push&status=success&per_page=${RUNS_TO_TRY}`, "--jq", "[.workflow_runs[].id]"));
  } catch (e) {
    warn(`${impl}: could not list main runs (${String(e.stderr ?? e.message).trim().split("\n")[0]})`);
    return undefined;
  }
  for (const id of runs) {
    const dir = mkdtempSync(join(tmpdir(), `conf-${impl}-`));
    try {
      gh("run", "download", String(id), "-R", repo, "-n", `${impl}-conformance-results`, "-D", dir);
      const f = join(dir, `${impl}-conformance.json`);
      if (existsSync(f)) return JSON.parse(readFileSync(f, "utf8"));
    } catch {
      // no artifact on this run (expired, or from before the summary existed): try the next one
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }
  return undefined;
}

const backends = {};
for (const impl of IMPLS) {
  const f = fromDir && join(fromDir, impl, `${impl}-conformance.json`);
  const found = fromDir ? (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : undefined) : fromCi(impl);
  if (found) {
    const { impl: _impl, ...figures } = found;
    backends[impl] = figures;
    console.log(`${impl}: run ${figures.run?.id ?? "?"} (${figures.run?.date ?? "?"})`);
  } else if (current.backends?.[impl]) {
    backends[impl] = current.backends[impl];
    warn(`${impl}: no conformance summary in its last ${RUNS_TO_TRY} passing main runs; keeping run ${current.backends[impl].run?.id ?? "?"} from the committed file`);
  } else {
    warn(`${impl}: no conformance figures; the table shows "next"`);
  }
}

const out = {
  $comment:
    "Generated by web/scripts/conformance-from-ci.mjs from each backend's latest passing CI run on main (CI regenerates it before every build). Do not edit by hand. Stack, response time and cold start are in catalogue.ts.",
  backends,
};
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
